const fs = require('fs');
const path = require('path');
const https = require('https');

const GEMINI_API_KEY = process.env.GEMINI_API_KEY;
const GEMINI_API_URL = 'https://generativelanguage.googleapis.com/v1beta/models/gemini-pro:generateContent';

const prompts = [
  'Write a 300-word article about forex market trends for beginner traders.',
  'Generate 5 engaging social media captions for a fintech startup.',
  'Create a news drop headline and summary about cryptocurrency regulations.'
];

async function generateContent(prompt) {
  return new Promise((resolve, reject) => {
    const requestPayload = JSON.stringify({
      contents: [{ parts: [{ text: prompt }] }]
    });

    const requestOptions = {
      hostname: 'generativelanguage.googleapis.com',
      path: `/v1beta/models/gemini-pro:generateContent?key=${GEMINI_API_KEY}`,
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Content-Length': requestPayload.length
      }
    };

    const httpsRequest = https.request(requestOptions, (res) => {
      let responseBody = '';
      res.on('data', (chunk) => responseBody += chunk);
      res.on('end', () => {
        try {
          const response = JSON.parse(responseBody);
          const generatedText = response.candidates[0].content.parts[0].text;
          resolve(generatedText);
        } catch (err) {
          reject(err);
        }
      });
    });

    httpsRequest.on('error', reject);
    httpsRequest.write(requestPayload);
    httpsRequest.end();
  });
}

async function main() {
  console.log('🤖 Starting content generation...');
  const outputDir = path.join(__dirname, '../public/generated');
  
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  for (let i = 0; i < prompts.length; i++) {
    try {
      console.log(`Generating content ${i + 1}/${prompts.length}...`);
      const content = await generateContent(prompts[i]);
      const filename = `content-${Date.now()}-${i}.html`;
      const html = `
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>global.press0 | Generated Content</title>
  <link rel="stylesheet" href="../assets/css/global-press0.css">
</head>
<body>
  <article class="gp0-article">
    <div class="gp0-content">${content}</div>
    <footer class="gp0-footer">
      <p>Generated by <strong>global.press0</strong> | ${new Date().toISOString()}</p>
    </footer>
  </article>
</body>
</html>
      `.trim();
      
      fs.writeFileSync(path.join(outputDir, filename), html);
      console.log(`✅ Saved: ${filename}`);
    } catch (err) {
      console.error(`❌ Error generating content ${i + 1}:`, err.message);
    }
  }
  
  console.log('✨ Content generation complete!');
}

main().catch(console.error);
